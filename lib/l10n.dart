/// Sprachsteuerung: null = Systemsprache folgen (Deutsch, wenn das System auf
/// Deutsch steht, sonst Englisch). Sonst 'de'/'en' manuell erzwungen.
final ValueNotifier<Locale?> localeNotifier = ValueNotifier<Locale?>(null);
const _localeKey = 'app_locale';

const List<Locale> kSupportedLocales = [Locale('de'), Locale('en')];

Future<void> loadLocale() async {
  final p = await SharedPreferences.getInstance();
  final c = p.getString(_localeKey);
  if (c == 'de' || c == 'en') localeNotifier.value = Locale(c!);
}

Future<void> setLocale(Locale? l) async {
  localeNotifier.value = l;
  final p = await SharedPreferences.getInstance();
  if (l == null) {
    await p.remove(_localeKey);
  } else {
    await p.setString(_localeKey, l.languageCode);
  }
}

/// Effektive Sprache: manueller Override, sonst Systemsprache.
String effLang() {
  final o = localeNotifier.value?.languageCode;
  final sys = WidgetsBinding.instance.platformDispatcher.locale.languageCode;
  return (o ?? sys) == 'de' ? 'de' : 'en';
}

/// Übersetzung nachschlagen (fällt auf Englisch, dann Key zurück).
String tr(String key) {
  final m = effLang() == 'de' ? _de : _en;
  return m[key] ?? _en[key] ?? key;
}

/// Wie [tr], ersetzt aber Platzhalter {name} durch die übergebenen Werte.
String trp(String key, Map<String, String> vars) {
  var s = tr(key);
  vars.forEach((k, v) => s = s.replaceAll('{$k}', v));
  return s;
}

